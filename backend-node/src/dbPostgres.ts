import pg from "pg";
import type { Db, Param } from "./db";

// Postgres behind the same Db interface as SQLite (DESIGN §13.3). Timestamps stay text in the
// "YYYY-MM-DD HH:MM:SS" UTC format SQLite uses, so API responses, comparisons and the dashboard are
// identical on both; moving to timestamptz would be a separate, additive change.

// count(*) and bigint ids come back as strings by default; every one of ours fits in a JS number.
pg.types.setTypeParser(pg.types.builtins.INT8, (v) => Number(v));
pg.types.setTypeParser(pg.types.builtins.NUMERIC, (v) => Number(v));

const NOW = `to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')`;

// `?` → `$1, $2, …`, skipping quoted text, so the same SQL runs on both databases.
export function toPositional(sql: string): string {
  let out = "";
  let n = 0;
  let quote: string | null = null;
  for (const ch of sql) {
    if (quote) {
      if (ch === quote) quote = null;
      out += ch;
    } else if (ch === "'" || ch === '"') {
      quote = ch;
      out += ch;
    } else if (ch === "?") {
      out += `$${++n}`;
    } else {
      out += ch;
    }
  }
  return out;
}

type Queryable = pg.Pool | pg.PoolClient;

function pgDb(pool: pg.Pool, client: pg.PoolClient | null): Db {
  const q: Queryable = client ?? pool;
  const query = (sql: string, params: Param[]) => q.query(toPositional(sql), params);
  const db: Db = {
    dialect: "postgres",
    now: NOW,
    inSeconds: `to_char(timezone('utc', now()) + make_interval(secs => ?), 'YYYY-MM-DD HH24:MI:SS')`,
    async all<T>(sql: string, ...params: Param[]) {
      return (await query(sql, params)).rows as T[];
    },
    async get<T>(sql: string, ...params: Param[]) {
      return (await query(sql, params)).rows[0] as T | undefined;
    },
    async run(sql, ...params) {
      return { changes: (await query(sql, params)).rowCount ?? 0 };
    },
    async exec(sql) {
      await q.query(sql);
    },
    async tx(fn, lock) {
      if (client) return fn(db);
      const c = await pool.connect();
      try {
        await c.query("begin");
        // Held until commit/rollback; other replicas asking for the same lock wait here.
        if (lock) await c.query("select pg_advisory_xact_lock(hashtext($1))", [lock]);
        const result = await fn(pgDb(pool, c));
        await c.query("commit");
        return result;
      } catch (err) {
        await c.query("rollback").catch(() => {});
        throw err;
      } finally {
        c.release();
      }
    },
    async close() {
      if (!client) await pool.end();
    },
  };
  return db;
}

// Waits for the database (it may still be starting next to us), then migrates. Retries use
// exponential backoff with a cap and jitter (SYSTEM.md I12).
export async function openPostgres(url: string, opts: { attempts?: number } = {}): Promise<Db> {
  const pool = new pg.Pool({ connectionString: url, max: 10, connectionTimeoutMillis: 5_000, idleTimeoutMillis: 30_000 });
  // An idle connection that breaks (database restart) must not crash the process; the pool replaces it.
  pool.on("error", () => {});
  const attempts = opts.attempts ?? 12;
  for (let i = 1; ; i++) {
    try {
      await pool.query("select 1");
      break;
    } catch (err) {
      if (i >= attempts) {
        await pool.end().catch(() => {});
        throw new Error(`Database: Postgres not reachable after ${attempts} attempts: ${(err as Error).message}`);
      }
      const delay = Math.min(500 * 2 ** (i - 1), 10_000) * (0.8 + Math.random() * 0.4);
      await new Promise((r) => setTimeout(r, delay));
    }
  }
  const db = pgDb(pool, null);
  await migratePostgres(db);
  return db;
}

// The same tables as SQLite (db.ts). Additive only (SYSTEM.md I10): new tables, and new columns
// with `add column if not exists`. Two replicas starting together migrate one after the other.
async function migratePostgres(db: Db) {
  await db.tx(async (t) => {
    await t.exec(`
      create table if not exists stores (
        id text primary key,
        name text,
        engine text not null,
        status text not null,
        namespace text not null,
        url text,
        user_id text,
        custom_domain text,
        domain_status text,
        domain_last_error text,
        last_backup_at text,
        created_by text,
        created_at text not null,
        updated_at text not null,
        last_error text,
        lease_owner text,
        lease_until text
      );

      create table if not exists store_events (
        id bigint generated by default as identity primary key,
        store_id text not null references stores(id) on delete cascade,
        type text not null,
        message text,
        actor text,
        ts text not null
      );

      create table if not exists users (
        id text primary key,
        name text not null,
        email text not null unique,
        password_hash text not null,
        created_at text not null,
        updated_at text not null,
        role text not null default 'member' check (role in ('admin','member')),
        disabled_at text
      );

      create table if not exists user_sessions (
        token text primary key,
        user_id text not null references users(id) on delete cascade,
        created_at text not null,
        expires_at text not null
      );

      create table if not exists billing_accounts (
        user_id text primary key references users(id) on delete cascade,
        provider text not null default 'stripe',
        plan_key text not null default 'growth',
        status text not null default 'inactive',
        billing_email text,
        stripe_customer_id text,
        stripe_subscription_id text,
        stripe_checkout_session_id text,
        stripe_price_id text,
        current_period_end text,
        created_at text not null,
        updated_at text not null
      );

      create table if not exists billing_invoices (
        id bigint generated by default as identity primary key,
        user_id text not null references users(id) on delete cascade,
        provider text not null,
        external_id text,
        amount_cents integer not null default 0,
        currency text not null default 'usd',
        status text not null,
        hosted_url text,
        invoice_pdf text,
        period_start text,
        period_end text,
        created_at text not null
      );

      create table if not exists store_backups (
        id bigint generated by default as identity primary key,
        store_id text not null references stores(id) on delete cascade,
        status text not null,
        file_path text,
        file_name text,
        size_bytes bigint,
        error text,
        started_at text not null,
        completed_at text,
        created_by text
      );

      create table if not exists leader_lock (
        name text primary key,
        owner text not null,
        lease_until text not null
      );

      create table if not exists invites (
        id text primary key,
        email text not null,
        role text not null check (role in ('admin','member')),
        token_hash text not null unique,
        invited_by text not null references users(id),
        expires_at text not null,
        accepted_at text,
        created_at text not null default ${NOW}
      );

      create table if not exists api_keys (
        id text primary key,
        user_id text not null references users(id),
        name text not null,
        prefix text not null unique,
        key_hash text not null,
        created_at text not null default ${NOW},
        last_used_at text,
        expires_at text,
        revoked_at text,
        revoked_by text
      );

      create table if not exists mcp_servers (
        id text primary key,
        slug text not null unique check (slug ~ '^[a-z]' and length(slug) <= 24),
        name text not null,
        url text not null,
        auth_type text not null default 'none' check (auth_type in ('none','bearer','header')),
        auth_header_name text,
        auth_secret_enc text,
        enabled integer not null default 1,
        timeout_ms integer not null default 15000,
        managed_by text not null default 'admin' check (managed_by in ('admin','helm','provisioner')),
        store_id text references stores(id),
        status text not null default 'Unknown',
        last_error text,
        last_ok_at text,
        last_check_at text,
        last_latency_ms integer,
        consecutive_failures integer not null default 0,
        created_at text not null default ${NOW},
        updated_at text not null default ${NOW}
      );

      create table if not exists mcp_tools (
        server_id text not null references mcp_servers(id) on delete cascade,
        name text not null,
        description text,
        input_schema text not null,
        annotations text,
        definition_hash text not null,
        approved_hash text,
        seen_at text not null,
        primary key (server_id, name)
      );

      create table if not exists tool_policies (
        server_id text not null references mcp_servers(id) on delete cascade,
        tool_name text not null,
        min_role text not null check (min_role in ('member','admin','nobody')),
        primary key (server_id, tool_name)
      );

      -- Append-only: no UPDATE or DELETE on this table anywhere in the code (SYSTEM.md I2).
      create table if not exists audit_log (
        id bigint generated by default as identity primary key,
        ts text not null default to_char(timezone('utc', now()), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
        request_id text not null,
        user_id text not null,
        user_email text not null,
        api_key_id text,
        source text not null check (source in ('mcp','chat')),
        server_id text,
        server_slug text,
        tool_name text not null,
        exposed_name text not null,
        duration_ms integer not null,
        outcome text not null check (outcome in ('ok','tool_error','timeout','unreachable','denied','not_found','bad_request')),
        error text,
        args_preview text
      );

      create table if not exists chat_approvals (
        id text primary key,
        user_id text not null,
        decision text check (decision in ('approved','declined')),
        created_at text not null default ${NOW},
        decided_at text
      );

      create index if not exists idx_store_events_store_ts on store_events(store_id, ts desc);
      create index if not exists idx_stores_status_created on stores(status, created_at);
      create index if not exists idx_stores_user_created on stores(user_id, created_at desc);
      create index if not exists idx_stores_domain_status on stores(domain_status, updated_at desc);
      create index if not exists idx_user_sessions_user on user_sessions(user_id, expires_at desc);
      create index if not exists idx_billing_invoices_user_created on billing_invoices(user_id, created_at desc);
      create unique index if not exists idx_billing_invoices_external on billing_invoices(provider, external_id);
      create index if not exists idx_store_backups_store_started on store_backups(store_id, started_at desc);
      create index if not exists idx_api_keys_user on api_keys(user_id, created_at desc);
      create index if not exists idx_invites_email on invites(email);
      create index if not exists idx_audit_ts on audit_log(ts desc);
      create index if not exists idx_audit_user on audit_log(user_id, ts desc);
    `);
  }, "schema-migration");
}
