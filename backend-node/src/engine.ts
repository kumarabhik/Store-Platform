export type EngineName = "woocommerce" | "medusa";

// Where our store chart (charts/store-woocommerce) lives inside the store-chart image that the
// Helm job runs. The chart is baked into the image, so provisioning needs no chart repository
// (DESIGN §11).
export const CHART_DIR = "/chart";

// Per-store Helm values for charts/store-woocommerce. Everything that is the same for every store
// in an environment comes from the chart's own values-<env>.yaml; only what differs per store is here.
// Credentials are not passed: the chart generates them once per release and keeps them (lookup +
// resource-policy: keep), so a retry or upgrade never rotates a database password (SYSTEM.md L4).
export function buildEngineValues(args: {
  engine: EngineName;
  ingressClassName: string;
  host: string;
  publicUrl: string;
  storeName: string;
  // Nightly backup CronJob on (its upload Secret was copied into the namespace, DESIGN §13.6).
  backup?: boolean;
}) {
  if (args.engine === "medusa") {
    return {
      valuesYaml: "",
      stubbed: true as const,
      reason: "medusa engine stubbed (not implemented in Round 1)",
    };
  }

  // JSON strings are valid YAML scalars, so a store name like `Bob's "Best": Shop` can't break the file.
  const q = (s: string) => JSON.stringify(s);
  const valuesYaml = [
    `publicUrl: ${q(args.publicUrl)}`,
    `ingress:`,
    `  className: ${q(args.ingressClassName)}`,
    `  host: ${q(args.host)}`,
    `site:`,
    `  title: ${q(args.storeName)}`,
    `  adminEmail: ${q(`admin@${args.host}`)}`,
    // values-prod.yaml points the default store at a pre-created Secret; every provisioned store
    // gets its own, generated by the chart.
    `existingSecret: ""`,
    `backup:`,
    `  enabled: ${args.backup ? "true" : "false"}`,
  ].join("\n");

  return { valuesYaml, stubbed: false as const };
}
